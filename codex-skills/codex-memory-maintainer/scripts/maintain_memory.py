def load_shard_entries(root: Path) -> list[LogEntry]:
    entries: list[LogEntry] = []
    for path in sorted((root / "wiki/logs").glob("[0-9][0-9][0-9][0-9]/[0-9][0-9][0-9][0-9]-[0-9][0-9].md"), reverse=True):
        entries.extend(parse_entries(path.read_text(encoding="utf-8")))
    return entries


def generated_targets(root: Path, entries: list[LogEntry], *, include_shards: bool) -> dict[Path, str]:
    targets = {
        root / "wiki/sources/_index.md": render_source_index(root),
        root / "wiki/generated/wiki-navigation.md": render_wiki_navigation(root),
        root / "wiki/logs/_index.md": render_log_index(entries),
        root / "wiki/log.md": render_compatibility_log(entries),
        root / "_index.md": render_root_index(root),
        root / "wiki/index.md": render_wiki_index(root),
    }
    if (root / CATALOG_PATH).is_file():
        catalog_entries = load_catalog(root).get("entries", [])
        targets[root / CATALOG_INDEX_PATH] = render_catalog_index(root)
        if any(str(item.get("kind", "")).startswith("project") for item in catalog_entries):
            targets[root / "wiki/projects.md"] = render_catalog_compatibility(root, "project")
        if any(item.get("kind") == "decision" for item in catalog_entries):
            targets[root / "wiki/decisions.md"] = render_catalog_compatibility(root, "decision")
    if include_shards:
        months: dict[str, list[LogEntry]] = {}
        for entry in entries:
            months.setdefault(entry.month, []).append(entry)
        for month, month_entries in months.items():
            targets[root / f"wiki/logs/{month[:4]}/{month}.md"] = render_shard(month, month_entries)
    return targets


def atomic_replace_many(targets: dict[Path, str]) -> None:
    staged: dict[Path, Path] = {}
    originals = {path: path.read_bytes() if path.exists() else None for path in targets}
    try:
        for path, text in targets.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            temp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
            with temp.open("w", encoding="utf-8") as handle:
                handle.write(text)
                handle.flush()
                os.fsync(handle.fileno())
            staged[path] = temp
        replaced: list[Path] = []
        try:
            for path, temp in staged.items():
                os.replace(temp, path)
                replaced.append(path)
        except Exception:
            for path in reversed(replaced):
                original = originals[path]
                if original is None:
                    path.unlink(missing_ok=True)
                else:
                    restore = path.with_name(f".{path.name}.{os.getpid()}.restore")
                    restore.write_bytes(original)
                    os.replace(restore, path)
            raise
    finally:
        for temp in staged.values():
            temp.unlink(missing_ok=True)


def migrate_legacy_log(root: Path) -> list[LogEntry]:
    if load_shard_entries(root):
        raise RuntimeError("canonical log shards already exist; refusing a second legacy migration")
    entries = parse_entries((root / "wiki/log.md").read_text(encoding="utf-8"))
    if not entries:
        raise RuntimeError("legacy wiki/log.md contains no dated entries")
    atomic_replace_many(generated_targets(root, entries, include_shards=True))
    return entries


def insert_entry(root: Path, entry_text: str) -> bool:
    parsed = parse_entries(entry_text.strip() + "\n")
    if len(parsed) != 1 or parsed[0].text.rstrip() != entry_text.strip():
        raise ValueError("entry must contain exactly one `## [YYYY-MM-DD] type | title` section")
    entry = parsed[0]
    entries = load_shard_entries(root)
    if any(existing.text == entry.text for existing in entries):
        atomic_replace_many(generated_targets(root, entries, include_shards=True))
        return False
    entries.append(entry)
    entries.sort(key=lambda item: item.date, reverse=True)
    atomic_replace_many(generated_targets(root, entries, include_shards=True))
    return True


def update_catalog_section(root: Path, stable_id: str, section_text: str) -> bool:
    """Atomically replace one governed catalog section and its integrity hash."""
    existing_issues = catalog_issues(root)
    if existing_issues:
        raise RuntimeError("catalog must be healthy before update: " + "; ".join(existing_issues))
    catalog = load_catalog(root)
    matches = [item for item in catalog.get("entries", []) if item.get("id") == stable_id]
    if len(matches) != 1:
        raise ValueError(f"catalog ID must match exactly one entry: {stable_id}")
    entry = matches[0]
    kind = str(entry.get("kind") or "")
    marker_by_kind = {
        "project": (
            "<!-- BEGIN LOSSLESS LEGACY PROJECT SECTION -->\n",
            "<!-- END LOSSLESS LEGACY PROJECT SECTION -->",
        ),
        "decision": (
            "<!-- BEGIN LOSSLESS LEGACY DECISION SECTION -->\n",
            "<!-- END LOSSLESS LEGACY DECISION SECTION -->",
        ),
    }
    marker_key = "project" if kind.startswith("project") else kind
    if marker_key not in marker_by_kind:
        raise ValueError(f"unsupported catalog kind for section update: {kind}")

    normalized = unicodedata.normalize("NFC", section_text.replace("\r\n", "\n").replace("\r", "\n"))
    if not normalized.endswith("\n"):
        normalized += "\n"
    expected_heading = f"## {entry.get('legacy_heading', '')}\n"
    if not normalized.startswith(expected_heading):
        raise ValueError(f"section must start with the unchanged legacy heading: {expected_heading.strip()}")
    if len(re.findall(r"(?m)^## ", normalized)) != 1:
        raise ValueError("catalog section must contain exactly one H2 heading")

    locator = str(entry.get("canonical_locator") or "")
    page_path = root / locator
    page = page_path.read_text(encoding="utf-8")
    start_marker, end_marker = marker_by_kind[marker_key]
    try:
        start = page.index(start_marker) + len(start_marker)
        end = page.index(end_marker, start)
    except ValueError as exc:
        raise ValueError(f"catalog page is missing governed section markers: {locator}") from exc
    digest = hashlib.sha256(normalized.encode("utf-8")).hexdigest()
    updated_page = page[:start] + normalized + page[end:]
    hash_pattern = re.compile(r"(?m)^- source section SHA-256：`[0-9a-f]{64}`$")
    if len(hash_pattern.findall(updated_page)) != 1:
        raise ValueError(f"catalog page must contain exactly one section hash metadata line: {locator}")
    updated_page = hash_pattern.sub(f"- source section SHA-256：`{digest}`", updated_page)
    entry["source_section_sha256"] = digest
    updated_catalog = json.dumps(catalog, ensure_ascii=False, indent=2) + "\n"

    catalog_path = root / CATALOG_PATH
    if page_path.read_text(encoding="utf-8") == updated_page and catalog_path.read_text(encoding="utf-8") == updated_catalog:
        return False
    atomic_replace_many({page_path: updated_page, catalog_path: updated_catalog})
    return True


def replace_entry_text(root: Path, old: str, new: str) -> bool:
    entries = load_shard_entries(root)
    matches = [index for index, entry in enumerate(entries) if old in entry.text]
    if not matches:
        if any(new in entry.text for entry in entries):
            return False
        raise ValueError("old log text not found in canonical shards")
    if len(matches) != 1:
        raise ValueError(f"old log text matched {len(matches)} entries")
    index = matches[0]
    updated = entries[index].text.replace(old, new)
    parsed = parse_entries(updated)
    if len(parsed) != 1:
        raise ValueError("replacement changed the entry boundary")
    entries[index] = parsed[0]
    atomic_replace_many(generated_targets(root, entries, include_shards=True))
    return True


def generation_issues(root: Path) -> list[str]:
    issues: list[str] = []
    issues.extend(catalog_issues(root))
    entries = load_shard_entries(root)
    if not entries:
        compatibility = root / "wiki/log.md"
        migrated = (root / "wiki/logs").exists() or (
            compatibility.exists() and GENERATED_NOTICE in compatibility.read_text(encoding="utf-8")
        )
        return ["no canonical monthly log shards found"] if migrated else []
    if any(entries[index].date < entries[index + 1].date for index in range(len(entries) - 1)):
        issues.append("canonical log entries are not reverse chronological")
    seen: set[str] = set()
    for entry in entries:
        digest = hashlib.sha256(entry.text.encode("utf-8")).hexdigest()
        if digest in seen:
            issues.append(f"duplicate canonical log entry: {entry.heading}")
        seen.add(digest)
    for path in sorted((root / "wiki/logs").glob("[0-9][0-9][0-9][0-9]/[0-9][0-9][0-9][0-9]-[0-9][0-9].md")):
        month = path.stem
        shard_entries = parse_entries(path.read_text(encoding="utf-8"))
        if any(entry.month != month for entry in shard_entries):
            issues.append(f"{path.relative_to(root)} contains an entry outside {month}")
    expected = generated_targets(root, entries, include_shards=True)
    for path, text in expected.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            issues.append(f"generated artifact drift: {path.relative_to(root)}")
    return issues


def catalog_issues(root: Path) -> list[str]:
    if not (root / CATALOG_PATH).is_file():
        return []
    try:
        entries = load_catalog(root).get("entries", [])
    except (OSError, ValueError, json.JSONDecodeError) as error:
        return [f"invalid catalog: {error}"]
    issues: list[str] = []
    seen_ids: set[str] = set()
    seen_locators: set[str] = set()
    seen_aliases: set[tuple[str, str]] = set()
    markers = {
        "project": (
            "<!-- BEGIN LOSSLESS LEGACY PROJECT SECTION -->\n",
            "<!-- END LOSSLESS LEGACY PROJECT SECTION -->",
            "wiki/catalog/projects/",
        ),
        "decision": (
            "<!-- BEGIN LOSSLESS LEGACY DECISION SECTION -->\n",
            "<!-- END LOSSLESS LEGACY DECISION SECTION -->",
            "wiki/catalog/decisions/",
        ),
    }
    for item in entries:
        stable_id = item.get("id")
        kind = item.get("kind")
        locator = item.get("canonical_locator")
        digest = item.get("source_section_sha256")
        if not isinstance(stable_id, str) or not stable_id:
            issues.append("catalog entry missing stable ID")
        elif stable_id in seen_ids:
            issues.append(f"duplicate catalog stable ID: {stable_id}")
        else:
            seen_ids.add(stable_id)
        if kind not in markers:
            issues.append(f"catalog entry {stable_id!r} has unsupported kind: {kind!r}")
            continue
        start_marker, end_marker, expected_prefix = markers[kind]
        if not isinstance(locator, str) or not locator.startswith(expected_prefix) or not locator.endswith(".md"):
            issues.append(f"catalog entry {stable_id!r} has invalid canonical locator: {locator!r}")
            continue
        if locator in seen_locators:
            issues.append(f"duplicate catalog canonical locator: {locator}")
        seen_locators.add(locator)
        aliases = item.get("aliases")
        if not isinstance(aliases, list) or not aliases:
            issues.append(f"catalog entry {stable_id!r} has no aliases")
        else:
            for alias in aliases:
                if not isinstance(alias, dict) or not isinstance(alias.get("type"), str) or not isinstance(alias.get("value"), str):
                    issues.append(f"catalog entry {stable_id!r} has invalid alias")
                    continue
                key = (alias["type"], alias["value"])
                if key in seen_aliases:
                    issues.append(f"duplicate catalog alias: {key[0]}={key[1]}")
                seen_aliases.add(key)
        if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
            issues.append(f"catalog entry {stable_id!r} has invalid section hash")
            continue
        page_path = root / locator
        if not page_path.is_file():
            issues.append(f"catalog entry {stable_id!r} locator does not exist: {locator}")
            continue
        page = page_path.read_text(encoding="utf-8")
        try:
            start = page.index(start_marker) + len(start_marker)
            end = page.index(end_marker, start)
        except ValueError:
            issues.append(f"catalog entry {stable_id!r} is missing lossless section markers")
            continue
        normalized = unicodedata.normalize("NFC", page[start:end].replace("\r\n", "\n").replace("\r", "\n"))
        actual = hashlib.sha256(normalized.encode("utf-8")).hexdigest()
        if actual != digest:
            issues.append(f"catalog entry {stable_id!r} section hash mismatch")
    return issues


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("migrate-log", "generate", "insert", "update-catalog-section"))
    parser.add_argument("--vault", type=Path, default=DEFAULT_VAULT)
    parser.add_argument("--entry-file", type=Path)
    parser.add_argument("--catalog-id")
    parser.add_argument("--section-file", type=Path)
    args = parser.parse_args()
    root = args.vault.expanduser().resolve()
    with exclusive_memory_maintenance_lock():
        if args.command == "migrate-log":
            entries = migrate_legacy_log(root)
            print(f"migrated {len(entries)} entries; sha256={entry_stream_sha256(entries)}")
        elif args.command == "generate":
            entries = load_shard_entries(root)
            if not entries:
                raise SystemExit("no canonical monthly log shards; run migrate-log first")
            atomic_replace_many(generated_targets(root, entries, include_shards=True))
            print(f"generated from {len(entries)} entries; sha256={entry_stream_sha256(entries)}")
        elif args.command == "insert":
            if not args.entry_file:
                raise SystemExit("insert requires --entry-file")
            changed = insert_entry(root, args.entry_file.read_text(encoding="utf-8"))
            print("inserted" if changed else "unchanged")
        else:
            if not args.catalog_id or not args.section_file:
                raise SystemExit("update-catalog-section requires --catalog-id and --section-file")
            changed = update_catalog_section(
                root,
                args.catalog_id,
                args.section_file.read_text(encoding="utf-8"),
            )
            print("updated" if changed else "unchanged")


if __name__ == "__main__":
    main()
