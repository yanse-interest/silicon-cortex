def render_shard(month: str, entries: list[LogEntry]) -> str:
    return "\n".join([
        f"# Wiki 维护日志 {month}", "", SHARD_NOTICE,
        "", "本月分片是维护日志的 canonical、lossless、倒序记录；只通过官方 helper 写入。", "",
        "\n".join(entry.text.rstrip() for entry in entries), "",
    ])


def render_log_index(entries: list[LogEntry]) -> str:
    months: dict[str, int] = {}
    for entry in entries:
        months[entry.month] = months.get(entry.month, 0) + 1
    lines = ["# Wiki 维护日志归档", "", GENERATED_NOTICE, "", "Canonical monthly shards，按月倒序。", ""]
    for month in sorted(months, reverse=True):
        year = month[:4]
        lines.append(f"- [[logs/{year}/{month}|{month}]] — {months[month]} entries")
    return "\n".join(lines) + "\n"


def render_compatibility_log(entries: list[LogEntry]) -> str:
    shown = entries[:CURRENT_ENTRY_LIMIT]
    newest = shown[0].date if shown else "none"
    oldest = shown[-1].date if shown else "none"
    return "\n".join([
        "# Wiki 维护日志", "", GENERATED_NOTICE, "",
        "此路径保留为兼容入口。完整、不可丢失的 canonical 历史位于 [[logs/_index|月度分片]]；新条目只通过官方 helper 写入。",
        f"当前窗口显示最新 {len(shown)} 条（{newest} → {oldest}），由 canonical shards 重建。", "",
        "\n".join(entry.text.rstrip() for entry in shown), "",
    ])


def _replace_block(text: str, block: str) -> str:
    rendered = f"{BLOCK_START}\n{block.rstrip()}\n{BLOCK_END}"
    pattern = re.compile(re.escape(BLOCK_START) + r".*?" + re.escape(BLOCK_END), re.S)
    if pattern.search(text):
        return pattern.sub(rendered, text)
    marker = "\n## 规则\n"
    if marker in text:
        return text.replace(marker, f"\n{rendered}\n{marker}", 1)
    return text.rstrip() + "\n\n" + rendered + "\n"


