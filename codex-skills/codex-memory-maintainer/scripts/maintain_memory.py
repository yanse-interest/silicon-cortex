@contextmanager
def exclusive_memory_maintenance_lock():
    """Prevent concurrent log/index read-modify-write transactions."""
    path = Path(os.environ.get("CODEX_MEMORY_MAINTENANCE_LOCK", DEFAULT_MAINTENANCE_LOCK.as_posix()))
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a+b") as stream:
        fcntl.flock(stream.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(stream.fileno(), fcntl.LOCK_UN)


@dataclass(frozen=True)
class LogEntry:
    date: str
    heading: str
    text: str

    @property
    def month(self) -> str:
        return self.date[:7]


def parse_entries(text: str) -> list[LogEntry]:
    matches = list(ENTRY_RE.finditer(text))
    entries: list[LogEntry] = []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        body = text[match.start():end].rstrip() + "\n"
        entries.append(LogEntry(match.group(1), match.group(0), body))
    return entries


def entry_stream_sha256(entries: list[LogEntry]) -> str:
    payload = "\n".join(entry.text.rstrip() for entry in entries).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def _frontmatter(text: str) -> dict[str, str]:
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---\n", 4)
    if end < 0:
        return {}
    result: dict[str, str] = {}
    for line in text[4:end].splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            result[key.strip()] = value.strip().strip('"\'')
    return result


def _title(text: str, fallback: str) -> str:
    match = re.search(r"(?m)^# (.+)$", text)
    return match.group(1).strip() if match else fallback


def _wiki_link(path: Path, root: Path) -> str:
    return path.relative_to(root / "wiki").with_suffix("").as_posix()


def render_source_index(root: Path) -> str:
    source_root = root / "wiki/sources"
    groups: dict[str, list[tuple[str, str, str, str]]] = {}
    names = {
        "conversations/chatgpt-daily": "ChatGPT 日报",
        "conversations/codex-daily": "Codex 日报",
        "reviews/weekly": "周度复盘",
        "docs": "架构文档",
        "travel": "旅行与地点综合",
    }
    for path in sorted(source_root.rglob("*.md")):
        if path.name == "_index.md":
            continue
        text = path.read_text(encoding="utf-8")
        meta = _frontmatter(text)
        relative_parent = path.relative_to(source_root).parent.as_posix()
        family = next((key for key in names if relative_parent == key or relative_parent.startswith(key + "/")), relative_parent)
        groups.setdefault(family, []).append(
            (
                meta.get("date", ""),
                _wiki_link(path, root),
                _title(text, path.stem),
                "/".join(filter(None, (meta.get("coverage", ""), meta.get("status", "")))),
            )
        )
    lines = ["# 来源索引", "", GENERATED_NOTICE, "", "本页是 source summary 文件的机械导航；来源解释与判断保留在各 source 页面。", ""]
    ordered_groups = sorted(groups, key=lambda key: (list(names).index(key) if key in names else 99, key))
    for family in ordered_groups:
        lines.extend([f"## {names.get(family, family)}", ""])
        for date, link, title, state in sorted(groups[family], key=lambda item: (item[0], item[1]), reverse=True):
            suffix = f" — `{state}`" if state else ""
            lines.append(f"- [[{link}|{title}]]{suffix}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_wiki_navigation(root: Path) -> str:
    excluded_prefixes = ("wiki/sources/", "wiki/logs/", "wiki/generated/")
    excluded_names = {"wiki/index.md", "wiki/log.md", "wiki/memory-system-health.md", "wiki/project-dashboard.md"}
    groups: dict[str, list[tuple[str, str]]] = {}
    for path in sorted((root / "wiki").rglob("*.md")):
        relative = path.relative_to(root).as_posix()
        if relative in excluded_names or relative.startswith(excluded_prefixes) or path.name == "_index.md":
            continue
        text = path.read_text(encoding="utf-8")
        if (root / CATALOG_PATH).is_file():
            catalog_entries = load_catalog(root).get("entries", [])
            if relative == "wiki/projects.md" and any(
                str(item.get("kind", "")).startswith("project") for item in catalog_entries
            ):
                text = render_catalog_compatibility(root, "project")
            elif relative == "wiki/decisions.md" and any(
                item.get("kind") == "decision" for item in catalog_entries
            ):
                text = render_catalog_compatibility(root, "decision")
        group = path.relative_to(root / "wiki").parts[0] if len(path.relative_to(root / "wiki").parts) > 1 else "核心页面"
        groups.setdefault(group, []).append((_wiki_link(path, root), _title(text, path.stem)))
    lines = ["# Wiki 机械导航", "", GENERATED_NOTICE, "", "本页只列路径与页面标题；内容优先级和阅读建议仍由 [[index|Wiki 索引]] 人工维护。", ""]
    for group in sorted(groups, key=lambda item: (item != "核心页面", item)):
        lines.extend([f"## {group}", ""])
        for link, title in sorted(groups[group]):
            lines.append(f"- [[{link}|{title}]]")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def load_catalog(root: Path) -> dict:
    path = root / CATALOG_PATH
    if not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("schema_version") != "1.0":
        raise ValueError(f"{CATALOG_PATH} must use schema_version 1.0")
    entries = data.get("entries")
    if not isinstance(entries, list):
        raise ValueError(f"{CATALOG_PATH}.entries must be an array")
    return data


def _catalog_link(locator: str) -> str:
    path, separator, anchor = locator.partition("#")
    if path.startswith("wiki/"):
        path = path[5:]
    return f"{path[:-3] if path.endswith('.md') else path}{separator}{anchor}"


def _catalog_title(entries: list[dict]) -> str:
    has_projects = any(str(item.get("kind", "")).startswith("project") for item in entries)
    has_decisions = any(item.get("kind") == "decision" for item in entries)
    if has_projects and has_decisions:
        return "项目与决策目录"
    if has_projects:
        return "项目目录"
    if has_decisions:
        return "决策目录"
    return "目录"


def render_catalog_index(root: Path) -> str:
    catalog = load_catalog(root)
    entries = catalog.get("entries", [])
    lines = [
        f"# {_catalog_title(entries)}",
        "",
        GENERATED_NOTICE,
        "",
        "本页只投影稳定 ID、标题与 canonical locator；正文与来源边界保留在 curated history 页面，Dashboard 当前字段仍由 registry 单独负责。",
        "",
    ]
    groups = (("project", "项目与项目背景"), ("decision", "决策"))
    for prefix, title in groups:
        selected = [item for item in entries if str(item.get("kind", "")).startswith(prefix)]
        if not selected:
            continue
        lines.extend([f"## {title}", ""])
        for item in selected:
            lines.append(
                f"- `{item['id']}` — [[{_catalog_link(item['canonical_locator'])}|{item['title']}]]"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


